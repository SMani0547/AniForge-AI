import { expect, test } from '@playwright/test';
import type { ApiEnvelope, Canvas, Scene } from '@aniforge/shared';
import { readFile } from 'node:fs/promises';
import { originalImage } from '../integration/fixture.js';

test('guest imports, edits, saves and reloads an actual editable scene through Firebase emulators', async ({ page }, testInfo) => {
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('/projects');
  await expect(page.getByText('Local Firebase emulators', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Continue as a guest' }).click();
  await expect(page.getByRole('heading', { name: 'A blank slate. All yours.' })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('baseline-dashboard-empty.png'), fullPage: true });
  await page.getByRole('button', { name: 'New project', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Project name').fill('Original geometric scene');
  await dialog.getByRole('button', { name: 'Create project', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Open Original geometric scene', exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('baseline-dashboard-populated.png'), fullPage: true });
  const firstScenes = page.waitForResponse((response) => /\/api\/v1\/projects\/[^/]+\/scenes$/.test(response.url()) && response.request().method() === 'GET');
  await page.getByRole('button', { name: 'Open Original geometric scene', exact: true }).click();
  const sceneResponse = await firstScenes;
  const first = ((await sceneResponse.json()) as ApiEnvelope<Scene[]>).data![0]!;
  const authorization = await sceneResponse.request().headerValue('authorization');
  expect(authorization).toMatch(/^Bearer /);
  const sceneUrl = `${sceneResponse.url()}/${first.id}`;
  const canvas = page.getByTestId('scene-canvas');
  await expect(canvas).toHaveAttribute('aria-label', 'Editable scene canvas with 0 objects');
  await page.screenshot({ path: testInfo.outputPath('baseline-editor-empty.png'), fullPage: true });
  async function savedScene() {
    const button = page.getByRole('button', { name: 'Save scene', exact: true });
    if (await button.isEnabled()) await button.click();
    await expect(page.getByRole('status').filter({ hasText: /^Saved .*revision \d+$/ })).toBeVisible();
    const response = await page.request.get(sceneUrl, { headers: { authorization: authorization! } });
    expect(response.status()).toBe(200);
    return ((await response.json()) as ApiEnvelope<Scene>).data!;
  }

  await page.getByRole('button', { name: 'Import image', exact: true }).click();
  const importer = page.getByRole('dialog', { name: 'Import an original image' });
  await importer.getByLabel('Original image', { exact: true }).setInputFiles({ name: 'original-geometry.png', mimeType: 'image/png', buffer: originalImage() });
  await expect(importer.getByLabel('Crop width', { exact: true })).toHaveValue('64');
  await importer.getByLabel('Crop width', { exact: true }).fill('48');
  await importer.getByLabel('Crop height', { exact: true }).fill('32');
  await importer.getByLabel('Crop x', { exact: true }).fill('8');
  await importer.getByLabel('Crop y', { exact: true }).fill('8');
  await expect(importer.getByRole('button', { name: 'Confirm crop and import' })).toBeDisabled();
  await importer.getByLabel('I created this image or have permission to use and animate it.').check();
  await importer.getByRole('button', { name: 'Confirm crop and import' }).click();
  await expect(importer).not.toBeVisible();
  await expect(canvas).toHaveAttribute('aria-label', 'Editable scene canvas with 1 objects');
  await page.getByLabel('Width', { exact: true }).fill('480');
  await page.getByLabel('Height', { exact: true }).fill('320');
  await page.getByLabel('X position', { exact: true }).fill('200');
  const imported = await savedScene();
  expect(imported.canvas.objects[0]).toMatchObject({ type: 'image', crop: { x: 8, y: 8, width: 48, height: 32 }, width: 480, height: 320, x: 200 });
  expect(imported.sourceAssetIds).toHaveLength(1);

  await page.getByRole('button', { name: 'Lock layer 1', exact: true }).click();
  await expect(page.getByLabel('X position', { exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Hide layer 1', exact: true }).click();
  const hidden = await savedScene();
  expect(hidden.canvas.objects[0]).toMatchObject({ locked: true, hidden: true });
  await page.getByRole('button', { name: 'Show layer 1', exact: true }).click();
  await page.getByRole('button', { name: 'Unlock layer 1', exact: true }).click();

  await page.getByRole('button', { name: 'Pencil', exact: true }).click();
  const box = await canvas.boundingBox();
  if (!box) throw new Error('Editable canvas is not visible');
  await page.mouse.move(box.x + box.width * 0.35, box.y + box.height * 0.55);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width * 0.7, box.y + box.height * 0.7, { steps: 10 });
  await page.mouse.up();
  await expect(canvas).toHaveAttribute('aria-label', 'Editable scene canvas with 2 objects');
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(canvas).toHaveAttribute('aria-label', 'Editable scene canvas with 1 objects');
  await page.getByRole('button', { name: 'Redo', exact: true }).click();
  await expect(canvas).toHaveAttribute('aria-label', 'Editable scene canvas with 2 objects');
  const beforeReload = await savedScene();
  expect(beforeReload.canvas.objects[1]).toMatchObject({ type: 'brushStroke', tool: 'brush' });
  if (beforeReload.canvas.objects[1]?.type === 'brushStroke') expect(beforeReload.canvas.objects[1].points.length).toBeGreaterThan(4);
  await page.screenshot({ path: testInfo.outputPath('saved-scene-before-reload.png'), fullPage: true });

  const restoredResponse = page.waitForResponse((response) => /\/api\/v1\/projects\/[^/]+\/scenes$/.test(response.url()) && response.request().method() === 'GET');
  await page.reload();
  const restored = ((await (await restoredResponse).json()) as ApiEnvelope<Scene[]>).data![0]!;
  await expect(canvas).toHaveAttribute('aria-label', 'Editable scene canvas with 2 objects');
  expect(restored.canvas).toEqual(beforeReload.canvas);
  expect(restored.sourceAssetIds).toEqual(beforeReload.sourceAssetIds);
  await page.getByRole('button', { name: /^Select layer 1:/ }).click();
  await expect(page.getByLabel('X position', { exact: true })).toHaveValue('200');
  await expect(page.getByLabel('Width', { exact: true })).toHaveValue('480');
  await expect(page.getByLabel('Image crop x', { exact: true })).toHaveValue('8');
  await expect(page.getByLabel('Image crop width', { exact: true })).toHaveValue('48');
  await page.getByLabel('Image crop x', { exact: true }).fill('12');
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(page.getByLabel('Image crop x', { exact: true })).toHaveValue('8');
  await page.getByRole('button', { name: 'Redo', exact: true }).click();
  await expect(page.getByLabel('Image crop x', { exact: true })).toHaveValue('12');
  await page.getByLabel('X position', { exact: true }).fill('350');
  const editedAgain = await savedScene();
  expect(editedAgain.canvas.objects[0]).toMatchObject({ id: beforeReload.canvas.objects[0]!.id, x: 350, crop: { x: 12, y: 8, width: 48, height: 32 } });
  expect(editedAgain.canvas.objects[1]).toEqual(beforeReload.canvas.objects[1]);
  expect(editedAgain.revision).toBeGreaterThan(beforeReload.revision);
  await page.screenshot({ path: testInfo.outputPath('saved-scene-after-reload.png'), fullPage: true });

  // Two browser tabs keep their own source changes when the server rejects a
  // stale revision; the user can export the unsaved work before recovering.
  const staleTab = await page.context().newPage();
  staleTab.on('pageerror', (error) => errors.push(error.message));
  await staleTab.goto(page.url());
  await expect(staleTab.getByTestId('scene-canvas')).toHaveAttribute('aria-label', 'Editable scene canvas with 2 objects');
  await page.getByRole('button', { name: 'Add rectangle', exact: true }).click();
  const winningScene = await savedScene();
  expect(winningScene.canvas.objects[2]?.type).toBe('rect');
  await staleTab.getByRole('button', { name: 'Add ellipse', exact: true }).click();
  await expect(staleTab.getByRole('status').filter({ hasText: 'Save conflict' })).toBeVisible();
  await expect(staleTab.getByRole('button', { name: 'Save scene', exact: true })).toBeDisabled();
  const downloadPromise = staleTab.waitForEvent('download');
  await staleTab.getByRole('button', { name: 'Download local scene', exact: true }).click();
  const download = await downloadPromise;
  const downloadPath = testInfo.outputPath('conflict-local-canvas.json');
  await download.saveAs(downloadPath);
  const local = JSON.parse(await readFile(downloadPath, 'utf8')) as { canvas: Canvas };
  expect(local.canvas.objects[2]?.type).toBe('ellipse');
  expect((await savedScene()).canvas).toEqual(winningScene.canvas);
  await staleTab.screenshot({ path: testInfo.outputPath('recoverable-save-conflict.png'), fullPage: true });
  staleTab.on('dialog', (dialog) => { void dialog.accept(); });
  await staleTab.getByRole('button', { name: 'Reload saved scene', exact: true }).click();
  await expect(staleTab.getByRole('button', { name: /^Select layer 3: Rectangle$/ })).toBeVisible();
  await expect(staleTab.getByRole('status').filter({ hasText: /^Saved .*revision \d+$/ })).toBeVisible();
  await staleTab.close();
  expect(errors).toEqual([]);
});
